class CountryRegistry:
    """Universal registry for all 249 ISO-3166-1 countries and territories."""

    _BY_ALPHA3: ClassVar[Dict[str, CountryInfo]] = {c.alpha3: c for c in _COUNTRY_DATA}
    _BY_ALPHA2: ClassVar[Dict[str, CountryInfo]] = {c.alpha2: c for c in _COUNTRY_DATA}
    _BY_NUMERIC: ClassVar[Dict[str, CountryInfo]] = {c.numeric: c for c in _COUNTRY_DATA}
    _ALL_COUNTRIES: ClassVar[List[CountryInfo]] = list(_COUNTRY_DATA)
    _ALL_ISO3: ClassVar[Set[str]] = {c.alpha3 for c in _COUNTRY_DATA}

    _LOOKUP_INDEX: ClassVar[Dict[str, CountryInfo]] = {}

    @classmethod
    def _init_index(cls) -> None:
        if cls._LOOKUP_INDEX:
            return
        idx: Dict[str, CountryInfo] = {}

        def _add(key: str, info: CountryInfo) -> None:
            clean = key.strip().lower()
            if clean:
                idx.setdefault(clean, info)
            # Alphanumeric only
            alnum = _RE_NON_ALNUM.sub("", clean)
            if alnum:
                idx.setdefault(alnum, info)
            # ASCII folded
            unaccent = (
                unicodedata.normalize("NFKD", clean)
                .encode("ASCII", "ignore")
                .decode("utf-8")
                .strip()
            )
            if unaccent and unaccent != clean:
                idx.setdefault(unaccent, info)
                unaccent_alnum = _RE_NON_ALNUM.sub("", unaccent)
                if unaccent_alnum:
                    idx.setdefault(unaccent_alnum, info)

        for c in _COUNTRY_DATA:
            _add(c.alpha2, c)
            _add(c.alpha3, c)
            _add(c.numeric, c)
            _add(c.numeric.lstrip("0"), c)
            _add(c.name, c)
            for native in c.native_names:
                _add(native, c)
            for alias in c.aliases:
                _add(alias, c)

        # The flat alias table in tables.COUNTRY_MAP and this registry must agree: every name the table knows resolves
        # here to the same country (registry entries win; the table only fills gaps such as "Burma" or "Ivory Coast").
        for alias_name, alpha3 in COUNTRY_MAP.items():
            info = cls._BY_ALPHA3.get(alpha3)
            if info is not None:
                _add(alias_name, info)

        cls._LOOKUP_INDEX = idx

    @classmethod
    def get(cls, query: Optional[str]) -> Optional[CountryInfo]:
        """Look up country by alpha-2, alpha-3, numeric code, name, or alias (case-insensitive)."""
        if not query:
            return None
        cls._init_index()
        q_raw = query.strip()
        if not q_raw:
            return None

        # Direct upper lookup
        q_upper = q_raw.upper()
        if q_upper in cls._BY_ALPHA3:
            return cls._BY_ALPHA3[q_upper]
        if q_upper in cls._BY_ALPHA2:
            return cls._BY_ALPHA2[q_upper]
        if q_raw in cls._BY_NUMERIC:
            return cls._BY_NUMERIC[q_raw]

        # Normalized lookup index
        q_lower = q_raw.lower()
        if q_lower in cls._LOOKUP_INDEX:
            return cls._LOOKUP_INDEX[q_lower]

        q_alnum = _RE_NON_ALNUM.sub("", q_lower)
        if q_alnum in cls._LOOKUP_INDEX:
            return cls._LOOKUP_INDEX[q_alnum]

        # Numeric stripped or padded
        if q_raw.isdigit():
            # (zero-padded numerics such as "36" are already indexed unpadded, so only the over-padded form lands here)
            unpadded = q_raw.lstrip("0")
            if unpadded in cls._LOOKUP_INDEX:
                return cls._LOOKUP_INDEX[unpadded]

        # Folded unicode lookup
        q_unaccent = (
            unicodedata.normalize("NFKD", q_lower)
            .encode("ASCII", "ignore")
            .decode("utf-8")
        )
        if q_unaccent in cls._LOOKUP_INDEX:
            return cls._LOOKUP_INDEX[q_unaccent]

        return None

    @classmethod
    def detect_country(
        cls,
        text: Optional[str],
        country_hint: Optional[str] = None,
    ) -> Optional[CountryInfo]:
        """Detect country from an address text string or country hint."""
        if country_hint:
            hint_info = cls.get(country_hint)
            if hint_info is not None:
                return hint_info

        if not text or not text.strip():
            return None

        t = text.strip()

        # Direct lookup of entire text
        direct = cls.get(t)
        if direct is not None:
            return direct

        # Check US State + ZIP pattern first (e.g. NY 10005)
        m_sz = RE_STATE_ZIP.search(t)
        if m_sz and m_sz.group(1).upper() in FROZEN_US_STATE_CODES:
            return cls.get("USA")

        # Check UK / Canadian postcodes
        if RE_UK_POSTCODE.search(t):
            return cls.get("GBR")
        if RE_CAN_POSTCODE.search(t):
            return cls.get("CAN")

        parts = [p.strip() for p in t.split(",") if p.strip()]
        if parts:
            # Check last segment
            p_last = parts[-1]
            if len(p_last) > 2 or p_last.upper() not in _IGNORE_2LETTER_COUNTRY:
                cand = cls.get(p_last)
                if cand is not None:
                    return cand

            subwords = p_last.split()
            if len(subwords) >= 2:
                two_w = f"{subwords[-2]} {subwords[-1]}"
                cand = cls.get(two_w)
                if cand is not None:
                    return cand
            if subwords and not subwords[-1].isdigit():
                last_w = subwords[-1]
                if len(last_w) > 2 or last_w.upper() not in _IGNORE_2LETTER_COUNTRY:
                    cand = cls.get(last_w)
                    if cand is not None:
                        return cand

            # Prioritize US state code/name to prevent domestic namesake cities
            # (e.g. Paris TX, London OH, Berlin CT, Montevideo MN, Rome GA, Lebanon NH, Mexico ME, Brazil IN)
            # from being hijacked by sovereign country names (on parts[-2]) or GLOBAL_METRO_TO_COUNTRY.
            # (a trailing "USA"/"United States" part was already resolved by the direct lookups above)
            last_clean = _RE_NON_WORD_SPACE.sub("", parts[-1]).strip().upper()
            if last_clean in FROZEN_US_STATE_CODES or last_clean in US_STATES:
                return cls.get("USA")
            sub_last = _RE_NON_WORD_SPACE.sub("", parts[-1].split()[-1]).strip().upper()
            if sub_last in FROZEN_US_STATE_CODES or sub_last in US_STATES:
                return cls.get("USA")

            # If last part had postal code or metro, check second to last part
            if len(parts) >= 2:
                p_prev = parts[-2]
                if len(p_prev) > 2:
                    cand = cls.get(p_prev)
                    if cand is not None:
                        return cand

        # Check Global Metros
        # Metro keys are ASCII: fold diacritics first ("Zürich" -> "ZURICH") so accented spellings still match.
        parts = [fold_to_ascii_key(p) for p in parts]
        for p in parts:
            p_clean = _RE_NON_ASCII_ALNUM_SPACE.sub(" ", p).strip().upper()
            p_clean = " ".join(p_clean.split())
            if p_clean in GLOBAL_METRO_TO_COUNTRY:
                return cls.get(GLOBAL_METRO_TO_COUNTRY[p_clean])

        # If comma-delimited, check subsequent segments (parts[1:]) rather than thoroughfare
        target_parts = parts[1:] if len(parts) > 1 else parts
        for p in target_parts:
            p_clean = _RE_NON_ASCII_ALNUM_SPACE.sub(" ", p).upper()
            p_words = p_clean.split()
            for n in (3, 2, 1):
                for i in range(len(p_words) - n, -1, -1):
                    cand = " ".join(p_words[i:i+n])
                    if cand in GLOBAL_METRO_TO_COUNTRY:
                        if n == 1:
                            # If followed by street suffix, it is a street name, not a municipality
                            if i + 1 < len(p_words) and p_words[i+1] in _ALL_STREET_SUFFIX_TOKENS:
                                continue
                        return cls.get(GLOBAL_METRO_TO_COUNTRY[cand])

        return None

    @classmethod
    def has_postal_codes(cls, query: str) -> bool:
        """Returns False for non-postal countries, True otherwise."""
        info = cls.get(query)
        if info is not None:
            return info.has_postal_codes
        return True

    @classmethod
    def all_countries(cls) -> List[CountryInfo]:
        """Returns list of all 249 ISO-3166-1 country records."""
        return list(cls._ALL_COUNTRIES)

    @classmethod
    def all_iso3(cls) -> Set[str]:
        """Returns set of all 249 ISO-3166-1 alpha-3 codes."""
        return set(cls._ALL_ISO3)
